  UGSGameplayAbility *g = gsa_inst(); g->rt = ab;
  g->bActivateAbilityOnGranted = u64_true(*u64_ivar(ab, "bActivateAbilityOnGranted")); g->bActivateOnInput = u64_true(*u64_ivar(ab, "bActivateOnInput"));
