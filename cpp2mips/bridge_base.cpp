UClass *rt_class(u64_v v)                                    // a Blueprint / native class value as a UClass that remembers the runtime value
{
  static UClass cls[64]; static u64_v val[64]; static int n;
  for (int i = 0; i < n; i++) if (val[i].t == v.t && val[i].u.o == v.u.o) return &cls[i];
  if (n >= 64) return nullptr;
  val[n] = v; cls[n].Name = nm_(v); cls[n].Rt = &val[n]; return &cls[n++];
}
FGameplayEffectSpecHandle make_spec_hook(void *ab, UClass *effect, int level)
{
  static FGameplayEffectSpec ring[64]; static u64_v rtv[64]; static int n;
  FGameplayEffectSpecHandle h; if (!effect || !effect->Rt) return h;
  u64_v args[2] = {*(u64_v *)effect->Rt, u64_int(level)};
  u64_v s = u64_call((u64_obj *)ab, "MakeOutgoingGameplayEffectSpec", 2, args);
  int k = n++ & 63; rtv[k] = s; ring[k] = FGameplayEffectSpec(); ring[k].Rt = &rtv[k]; h.Data = &ring[k]; return h;
}
