    CHECK(n >= 1 && h[n - 1].blocking && !h[n - 1].actor && fabsf(h[n - 1].loc[0] - 4880.0f) < 0.01f && fabsf(h[n - 1].normal[0] + 1.0f) < 1e-4f);
